#ifndef SCAN_TASK_H
#define SCAN_TASK_H

#include <Arduino.h>

// ============================================================================
// НЕБЛОКИРУЮЩИЕ СКАНИРОВАНИЯ (P1-8)
// ============================================================================
// Скан геометрии и калибровка карты провиса идут одним движком по шагам:
// позиционирование -> пауза на вибрации -> замер -> следующая точка.
// За один вызов updateScanTask() делается не больше одного шага, поэтому
// supervisorTask продолжает обслуживать телеметрию и Wi-Fi (включая ESTOP).
// ============================================================================

// Запуск скана геометрии вдоль X (машинные координаты, Y/Z = 0).
// Проверяет параметры и сам переводит FSM в STATE_CALIBRATION.
// false = параметры отклонены или переход запрещён (причина уже отправлена).
bool startGeometryScan(float startX, float endX, float stepX, float feedRateMM_Sec);

// Запуск калибровки карты провиса по cfg.laserMapSize / cfg.laserGridStep.
// Точки: X = i * laserGridStep, i = 0…laserMapSize-1, замер только камерой.
bool startLaserMapCalibration();

// Один шаг движка. Вызывать из supervisorTask на каждом круге.
void updateScanTask();

// true = скан/калибровка выполняются (FSM держит STATE_CALIBRATION).
bool isScanActive();

#endif
